# conversion of int into float
value = 10  # integer value
a = float(value)
print("value of a : ",a)
print("type(a) : ",type(a))

# conversion of float into int
value = 10.54  # float value
a = int(value)
print("value of a : ",a)
print("type(a) : ",type(a))

# conversion of int into complex
value = 10  # integer value
a = complex(value)
print("value of a : ",a)
print("type(a) : ",type(a))
print("real : ",a.real)
print("imag : ",a.imag)

