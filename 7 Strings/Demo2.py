# example showing the concept of string

name = "Jacob"
print("Name : ",name);
print("name[0] : ",name[0]);
print("name[1] : ",name[1]);
print("name[2] : ",name[2]);
print("name[3] : ",name[3]);
print("name[4] : ",name[4]);

print(end="\n");

print("name[-1] : ",name[-1]);
print("name[-2] : ",name[-2]);
print("name[-3] : ",name[-3]);
print("name[-4] : ",name[-4]);
print("name[-5] : ",name[-5]);

